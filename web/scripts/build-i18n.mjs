// Builds public/assets/i18n.js for the web pages.
//
// Keys are the English source strings. Translations come first from the iOS
// string catalogs (so web and app say the same thing), then from
// i18n/web.json for strings that only exist on the web.
//
//   node scripts/build-i18n.mjs          build
//   node scripts/build-i18n.mjs --check  fail if a UI string has no translation

import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(root, "..");
const LANGS = ["ar", "tr", "id", "ur"];

function catalog(file) {
  const out = {};
  const { strings } = JSON.parse(readFileSync(file, "utf8"));
  for (const [key, entry] of Object.entries(strings)) {
    for (const lang of LANGS) {
      const value = entry.localizations?.[lang]?.stringUnit?.value;
      if (value) (out[lang] ||= {})[key] = value;
    }
  }
  return out;
}

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

// Every string literal in the page scripts and every data-t attribute.
export function collectKeys(files) {
  const keys = new Set();
  const called = new Set();
  for (const file of files) {
    const src = readFileSync(file, "utf8");
    if (file.endsWith(".html")) {
      for (const m of src.matchAll(/data-t(?:-aria)?="([^"]+)"/g)) {
        const key = m[1].replace(/&amp;/g, "&").replace(/&#39;/g, "'").replace(/&quot;/g, '"');
        keys.add(key);
        called.add(key);
      }
      continue;
    }
    for (const m of src.matchAll(/"((?:[^"\\\n]|\\.)*)"/g)) {
      try {
        keys.add(JSON.parse(`"${m[1]}"`));
      } catch {
        /* not a plain string */
      }
    }
    for (const m of src.matchAll(/\bt\(\s*"((?:[^"\\\n]|\\.)*)"/g)) called.add(JSON.parse(`"${m[1]}"`));
  }
  return { keys, called };
}

const ios = [
  catalog(join(repo, "Ramadan Pro/Resources/Localizable.xcstrings")),
  catalog(join(repo, "Ramadan Pro/Resources/CoreLocalizable.xcstrings")),
];
const web = JSON.parse(readFileSync(join(root, "i18n/web.json"), "utf8"));

const files = walk(join(root, "public")).filter((f) => /\.(js|html)$/.test(f) && !f.endsWith("i18n.js"));
const { keys, called } = collectKeys(files);
for (const key of Object.keys(web.en || {})) keys.add(key);

const out = {};
const missing = new Map();
for (const lang of LANGS) {
  out[lang] = {};
  for (const key of keys) {
    const value = web[lang]?.[key] ?? ios[0][lang]?.[key] ?? ios[1][lang]?.[key];
    if (value) out[lang][key] = value;
    else if (called.has(key) || key in (web.en || {})) (missing.get(key) || missing.set(key, []).get(key)).push(lang);
  }
}

writeFileSync(
  join(root, "public/assets/i18n.js"),
  `// Generated by scripts/build-i18n.mjs. Do not edit; change i18n/web.json or the iOS catalogs.\nwindow.SA_I18N = ${JSON.stringify(out)};\n`,
);

const counts = LANGS.map((l) => `${l} ${Object.keys(out[l]).length}`).join(", ");
console.log(`i18n.js written (${counts})`);
if (missing.size) {
  console.log(`\n${missing.size} UI strings without a translation:`);
  for (const [key, langs] of missing) console.log(`  ${JSON.stringify(key)}  [${langs.join(",")}]`);
  if (process.argv.includes("--check")) process.exit(1);
}
